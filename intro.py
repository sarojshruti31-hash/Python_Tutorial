# Object Oriented Programming -> (Classes and Objects)
# -> Mapping real world objects
# Eg: Factory --> Class is a blueprint of an object and Object is an instance of a class

class Student:
    subject = "Python"
    college = "ABC"
    year = "4th year"
stu1 = Student()
stu2 = Student()
print(stu1.subject, stu1.college, stu1.year)
print(stu2.subject, stu2.college, stu2.year)

